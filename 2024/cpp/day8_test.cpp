#include "check.hpp"
#include "day8.hpp"

int main() {
    {
        std::string_view example = R"(............
........0...
.....0......
.......0....
....0.......
......A.....
............
............
........A...
.........A..
............
............)";
        auto [p1, p2] = day8::solve(example);
        check::equal(p1, 14LL);
        check::equal(p2, 34LL);
    }

    check::throws([]() { day8::solve(""); });
    check::throws([]() { day8::solve("...\n..\n..."); });

    return check::exit_code();
}
